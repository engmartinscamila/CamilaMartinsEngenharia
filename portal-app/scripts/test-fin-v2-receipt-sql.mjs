import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
const requireIsolated=createRequire(path.join(process.env.CME_FIN_SQL_ROOT??path.resolve('../../finance-v2-test'),'index.js'));
const {PGlite}=requireIsolated('@electric-sql/pglite');
const db=new PGlite();
const uuid=n=>'00000000-0000-4000-8000-'+String(n).padStart(12,'0');
const user=uuid(1),client=uuid(10),secondClient=uuid(11),payReq=uuid(20),paymentId=uuid(21),receiptRequest=uuid(30);
const setup=`
create schema auth;create role authenticated;create role anon;
create function auth.uid() returns uuid language sql stable as $$select '${user}'::uuid$$;
create function public.is_portal_admin() returns boolean language sql stable as $$select true$$;
create table public.clientes(id uuid primary key,nome text not null);
create table public.contratos(id uuid primary key,cliente_id uuid not null references public.clientes(id));
create table public.projetos(id uuid primary key,cliente_id uuid not null references public.clientes(id),contract_id uuid references public.contratos(id));
create table public.financial_accounts(id uuid primary key);
create table public.audit_log(id uuid primary key default gen_random_uuid(),user_id uuid,action text,entity_type text,entity_id uuid,details jsonb,created_at timestamptz default now());
`;
await db.exec(setup);
await db.exec(fs.readFileSync('../docs/finance-v2/0001-financial-ledger-candidate.sql','utf8'));
await db.exec(fs.readFileSync('../docs/finance-v2/0002-receipt-evidence-candidate.sql','utf8'));
const query=(sql,args=[])=>db.query(sql,args);
const one=async(sql,args=[])=> (await query(sql,args)).rows[0];
await query('insert into public.clientes(id,nome) values ($1,$2),($3,$4)',[client,'Cliente de teste',secondClient,'Outra pessoa']);
const draft={request_id:payReq,client_id:client,account_id:null,amount:125.75,paid_on:'2026-11-07',payment_method:'Pix',allocations:[]};
const id=(await one('select public.admin_fin_v2_record_payment($1::jsonb) as id',[JSON.stringify(draft)])).id;
assert(id);
const result=await one('select public.admin_fin_v2_issue_receipt_reference($1,$2) as id',[id,receiptRequest]);
const receiptId=result.id;
assert(receiptId);
assert.equal((await one('select public.admin_fin_v2_issue_receipt_reference($1,$2) as id',[id,receiptRequest])).id,receiptId,'Repetição idempotente');
let count=await one('select count(*)::int as n from public.fin_v2_receipt_records');
assert.equal(count.n,1,'Uma prova por pagamento');
const stored=await one('select reference_number,immutable_snapshot from public.fin_v2_receipt_records where id=$1',[receiptId]);
assert(stored.reference_number>0);
assert.equal(stored.immutable_snapshot.client_name,'Cliente de teste');
assert.equal(stored.immutable_snapshot.payment_amount,125.75);
assert.equal(stored.immutable_snapshot.document_is_final,false);
assert.equal(stored.immutable_snapshot.kind,'comprovante_administrativo_homologacao');
await query('update public.clientes set nome=$1 where id=$2',['Nome novo',client]);
assert.equal((await one('select immutable_snapshot from public.fin_v2_receipt_records where id=$1',[receiptId])).immutable_snapshot.client_name,'Cliente de teste','Snapshot não é reescrito pelo cadastro');
await assert.rejects(()=>query('select public.admin_fin_v2_issue_receipt_reference($1,$2)',[id,uuid(31)]),/já vinculado/);
const second={...draft,request_id:uuid(22)};
const secondId=(await one('select public.admin_fin_v2_record_payment($1::jsonb) as id',[JSON.stringify(second)])).id;
await assert.rejects(()=>query('select public.admin_fin_v2_issue_receipt_reference($1,$2)',[secondId,receiptRequest]),/reutilizado/);
await query('select public.admin_fin_v2_reverse_payment($1,$2,$3)',[secondId,uuid(32),'Pagamento devolvido']);
await assert.rejects(()=>query('select public.admin_fin_v2_issue_receipt_reference($1,$2)',[secondId,uuid(33)]),/estornado/);
await query('select public.admin_fin_v2_reverse_payment($1,$2,$3)',[id,uuid(34),'Pagamento devolvido']);
assert.equal((await one('select count(*)::int as n from public.fin_v2_receipt_records')).n,1,'Comprovante original permanece para auditoria após estorno');
assert.equal((await one('select count(*)::int as n from public.fin_v2_payments')).n,2,'Nenhum segundo pagamento criado pelo comprovante');
await query('set role authenticated');
await assert.rejects(()=>query('insert into public.fin_v2_receipt_records(payment_id,request_id,immutable_snapshot,issued_by) values($1,$2,\'{}\',$3)',[id,uuid(35),user]),/permission denied|row-level security/);
await query('reset role');
await query('create or replace function public.is_portal_admin() returns boolean language sql stable as $$select false$$');
await query('set role authenticated');
assert.equal((await one('select count(*)::int as n from public.fin_v2_receipt_records')).n,0,'RLS nega consulta ao não-administrador');
await query('reset role');
await db.close();
console.log('PASS: comprovante V2 SQL — vínculo único pagamento/registro, idempotência, snapshot, estorno, caixa não duplicado e RLS.');
