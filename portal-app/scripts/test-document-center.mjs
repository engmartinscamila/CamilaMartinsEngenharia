import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const exports={};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('src/lib/document-center-model.ts','utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS}}).outputText,{exports,Set});
const m=exports;
const root={id:'d1',kind:'anexo_i',status:'gerado'},revision={id:'d2',kind:'anexo_i',revisionOf:'d1',status:'enviado'},other={id:'unrelated',kind:'anexo_i',status:'rascunho'};
assert.deepEqual(Array.from(m.documentFamily(revision,[revision,root,other]),row=>row.id),['d2','d1'],'Não mistura documentos independentes do mesmo tipo');
assert.equal(m.documentState({...root,supersededAt:'2026-01-01'},[],[{documentId:'d1',decision:'accepted'}]),'substituido');
assert.equal(m.documentState(revision,[],[{documentId:'d2',decision:'rejected'}]),'recusado');
assert.equal(m.documentState(revision,[{documentId:'d2',lifecycleStatus:'expirado'}],[{documentId:'d2',decision:'accepted'}]),'expirado');
assert.equal(m.documentState({...revision,releasedAt:'2026-01-01',acceptanceRequired:true},[],[]),'aguardando_aceite');
assert.equal(m.matchesDocumentFilter('aguardando_aceite',true,'overdue'),true);
assert.equal(m.matchesDocumentFilter('aceito',false,'waiting'),false);
assert.equal(m.matchesDocumentFilter('aceito_com_ressalvas',false,'accepted'),true);
assert.equal(m.isDocumentDecision({type:'Documento'}),true);
assert.equal(m.isDocumentDecision({type:'Layout',relatedDocumentId:'d1'}),false,'Uma decisão de layout mantém sua natureza mesmo com referência documental');
assert.equal(m.normalizeDocumentSearch('Aprovação — Revisão'),'aprovacao — revisao');
console.log('PASS: famílias de versões, substituição, validade, aceites, filtros e decisões de projeto.');
