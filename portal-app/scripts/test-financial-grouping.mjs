import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const module={exports:{}};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('src/lib/financial-grouping.ts','utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS}}).outputText,{module,exports:module.exports});
const {groupFinancialClients,groupFinancialProjects,groupStatementClients}=module.exports;
const entry=(id,clientId,projectId)=>({id,clientId,projectId,clientName:'Mesmo nome',projectName:'Mesmo projeto',contractNumber:'CON-1',description:'Parcela '+id});
const rows=[entry('10','A','P'),entry('2','A','P'),entry('1','B','Q'),entry('3','A','R'),entry('4','A',null)];
const clients=groupFinancialClients(rows);
assert.equal(clients.length,2,'Clientes homônimos permanecem separados por UUID');
assert.equal(clients.find(c=>c.id==='A').entries.length,4,'Um cliente mantém todas as suas parcelas na mesma página');
const projects=groupFinancialProjects(clients.find(c=>c.id==='A').entries);
assert.equal(projects.length,3,'Projetos homônimos e serviço avulso não se misturam');
assert.deepEqual(Array.from(projects.find(p=>p.id==='P').entries,r=>r.id),['2','10'],'Ordenação numérica das parcelas');
assert.equal(projects.find(p=>p.id==='without-project').name,'Serviços sem projeto');
assert.equal(rows[0].id,'10','Agrupamento não altera os lançamentos originais');
assert.equal(groupStatementClients([{id:'C1',clientId:'A',clientName:'Mesmo nome'},{id:'C2',clientId:'A',clientName:'Mesmo nome'},{id:'C3',clientId:'B',clientName:'Mesmo nome'}]).length,2);
assert.equal(groupFinancialClients([entry('x',null,null),entry('y',null,null)]).length,2,'Origens desconhecidas não são unidas pelo nome');
console.log('PASS: clientes e projetos por UUID, homônimos separados, serviços avulsos, parcelas ordenadas e paginação sem dividir cliente.');
