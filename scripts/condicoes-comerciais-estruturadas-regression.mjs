import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=p=>fs.readFileSync(p,'utf8');
const main=read('js/commercial-documents-web.js');
const html=read('orcamentos-contratos.html');
const terms=read('js/commercial-terms-web.js');
const preview=read('js/commercial-document-preview-web.js');
const master=read('portal-app/supabase/functions/_shared/commercial-word-renderer.ts');
const annex=read('portal-app/supabase/functions/generate-contract-document/index.ts');
const migration=read('docs/COMERCIAL_CONDICOES_ESTRUTURADAS.sql');
assert.ok(html.includes('commercial-terms-web.js'),'Editor deve carregar na central');
assert.ok(main.includes('data-action="commercial-terms"'),'Ação de edição no histórico');
assert.ok(main.includes('CMEEditCommercialTerms(recordId)'),'Primeira emissão exige condições comerciais');
assert.ok(preview.includes("select('commercial_terms')"),'Revisão deve consultar dados estruturados');
assert.ok(terms.includes('admin_save_commercial_terms'),'Persistência segura pelo RPC administrativo');
assert.ok(terms.includes('A soma das parcelas deve ser exatamente'),'Validação monetária na interface');
assert.ok(terms.includes('scopeRows')&&terms.includes('days')&&terms.includes('deliverables'),'Editor precisa registrar quantitativos e prazo por serviço');
assert.ok(migration.includes('assert_commercial_terms_ready'),'Validação obrigatória no servidor');
assert.ok(migration.includes('abs(v_sum-p_total)>0.009'),'Confere soma das parcelas em centavos');
assert.ok(migration.includes("p_document_kind='anexo_i'"),'Anexo também exige dados completos');
assert.ok(master.includes('scopeQuantityRows(record)'),'Word do contrato deve apresentar quantitativos');
assert.ok(annex.includes('QUANTITATIVO CONTRATADO'),'Anexo deve discriminar quantitativos específicos');
assert.equal(read('supabase/functions/_shared/commercial-word-renderer.ts'),master,'Geradores comerciais espelhados idênticos');
assert.equal(read('supabase/functions/generate-contract-document/index.ts'),annex,'Geradores do anexo espelhados idênticos');
console.log('PASS: editor, persistência, validação de valores, prazo, quantitativos, Word e Anexo I.');
